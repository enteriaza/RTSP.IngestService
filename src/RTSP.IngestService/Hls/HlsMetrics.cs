// System.Diagnostics.Metrics instruments for HLS packaging and segment storage, created from the host's
// IMeterFactory. Tags are fixed enumerations (segment boundary, error kind, eviction reason, track); stream names,
// identities, session IDs and segment names are never used as tags.

using System.Diagnostics.Metrics;

namespace RTSP.IngestService.Hls;

/// <summary>Why a media segment was closed.</summary>
internal enum HlsSegmentBoundary
{
    /// <summary>At a video sync sample (or, audio-only, an audio frame) at or after the target duration.</summary>
    Keyframe,

    /// <summary>The maximum segment duration or size was reached without a sync sample.</summary>
    Forced,

    /// <summary>A codec configuration change starts a new initialization segment.</summary>
    Configuration,

    /// <summary>A timestamp discontinuity or dropped media starts a new timeline.</summary>
    Discontinuity,

    /// <summary>The publisher stopped; the segment holds what had arrived.</summary>
    Final,
}

/// <summary>A packaging problem.</summary>
internal enum HlsErrorKind
{
    /// <summary>A track's codec configuration cannot be packaged (for example an unsupported AAC object type).</summary>
    UnsupportedTrack,

    /// <summary>A track's configuration is invalid for packaging (for example an SPS without valid dimensions).</summary>
    InvalidTrack,

    /// <summary>A segment would exceed the maximum segment or initialization size.</summary>
    SegmentTooLarge,

    /// <summary>The store could not retain a segment.</summary>
    StorageFull,

    /// <summary>The live playlist is at its entry cap and cannot shrink below three target durations.</summary>
    PlaylistFull,
}

/// <summary>HLS packaging metrics, published on the <see cref="MeterName"/> meter.</summary>
/// <remarks>Thread-safe.</remarks>
internal sealed class HlsMetrics
{
    /// <summary>Name of the meter.</summary>
    public const string MeterName = "RTSP.IngestService.Hls";

    /// <summary>Streams being packaged.</summary>
    private readonly UpDownCounter<long> _sessions;

    /// <summary>Initialization segments generated.</summary>
    private readonly Counter<long> _initializations;

    /// <summary>Media segments generated by boundary.</summary>
    private readonly Counter<long> _segments;

    /// <summary>Segment bytes generated.</summary>
    private readonly Counter<long> _segmentBytes;

    /// <summary>Media segment durations.</summary>
    private readonly Histogram<double> _segmentDuration;

    /// <summary>Time beyond the target spent waiting for a sync sample.</summary>
    private readonly Histogram<double> _keyframeWait;

    /// <summary>Bytes held by the segment store.</summary>
    private readonly UpDownCounter<long> _storageBytes;

    /// <summary>Evicted segments by reason.</summary>
    private readonly Counter<long> _evictions;

    /// <summary>Packaging errors by kind.</summary>
    private readonly Counter<long> _errors;

    /// <summary>Discontinuities by reason.</summary>
    private readonly Counter<long> _discontinuities;

    /// <summary>Samples not packaged by track and reason.</summary>
    private readonly Counter<long> _droppedSamples;

    /// <summary>Sample bytes held for segments being built.</summary>
    private readonly UpDownCounter<long> _pendingBytes;

    /// <summary>Segment requests refused by the reader memory budget.</summary>
    private readonly Counter<long> _readerRefusals;

    /// <summary>Bytes of distinct segments held by readers.</summary>
    private readonly UpDownCounter<long> _readerBytes;

    /// <summary>Bytes of pooled segment chunks by state.</summary>
    private readonly UpDownCounter<long> _poolBytes;

    /// <summary>Initializes a new instance of the <see cref="HlsMetrics"/> class.</summary>
    /// <param name="meterFactory">Factory owning the meter's lifetime.</param>
    public HlsMetrics(IMeterFactory meterFactory)
    {
        ArgumentNullException.ThrowIfNull(meterFactory);
        var meter = meterFactory.Create(MeterName);
        _sessions = meter.CreateUpDownCounter<long>("hls.sessions.active", "{session}", "Streams being packaged.");
        _initializations = meter.CreateCounter<long>("hls.initialization_segments", "{segment}", "Initialization segments generated.");
        _segments = meter.CreateCounter<long>("hls.segments", "{segment}", "Media segments generated; tag boundary.");
        _segmentBytes = meter.CreateCounter<long>("hls.segment_bytes", "By", "Bytes of generated initialization and media segments.");
        _segmentDuration = meter.CreateHistogram<double>("hls.segment.duration", "s", "Durations of generated media segments.");
        _keyframeWait = meter.CreateHistogram<double>("hls.keyframe_wait", "s", "Media time beyond the target duration spent waiting for a video sync sample.");
        _storageBytes = meter.CreateUpDownCounter<long>("hls.storage.bytes", "By", "Bytes held by the segment store.");
        _evictions = meter.CreateCounter<long>("hls.storage.evictions", "{segment}", "Segments released by the store; tag reason.");
        _errors = meter.CreateCounter<long>("hls.errors", "{error}", "Packaging errors; tag kind.");
        _discontinuities = meter.CreateCounter<long>("hls.discontinuities", "{discontinuity}", "Playlist discontinuities; tag reason.");
        _droppedSamples = meter.CreateCounter<long>("hls.samples.dropped", "{sample}", "Samples not packaged; tags track and reason.");
        _pendingBytes = meter.CreateUpDownCounter<long>("hls.pending.bytes", "By", "Sample bytes held for segments being built.");
        _readerRefusals = meter.CreateCounter<long>("hls.readers.refused", "{request}", "Segment requests refused because the reader memory budget was exhausted.");
        _readerBytes = meter.CreateUpDownCounter<long>("hls.readers.bytes", "By", "Bytes of distinct segments held by readers, stored or already evicted.");
        _poolBytes = meter.CreateUpDownCounter<long>("hls.segment_pool.bytes", "By", "Bytes of pooled segment chunks; tag state (in_use or free).");
    }

    /// <summary>Records a change in the bytes of distinct segments held by readers.</summary>
    /// <param name="delta">Bytes reserved (positive) or returned (negative).</param>
    public void ReaderMemoryChanged(long delta) => _readerBytes.Add(delta);

    /// <summary>Records a change in pooled segment chunks.</summary>
    /// <param name="inUse">Change in bytes of chunks held by segments.</param>
    /// <param name="free">Change in bytes of free chunks kept for reuse.</param>
    public void PoolChanged(long inUse, long free)
    {
        _poolBytes.Add(inUse, new KeyValuePair<string, object?>("state", "in_use"));
        if (free != 0)
        {
            _poolBytes.Add(free, new KeyValuePair<string, object?>("state", "free"));
        }
    }

    /// <summary>Records a change in sample bytes held for segments being built.</summary>
    /// <param name="delta">Bytes added (positive) or released (negative).</param>
    public void PendingChanged(long delta) => _pendingBytes.Add(delta);

    /// <summary>Records a segment request refused by the reader memory budget.</summary>
    public void ReaderRefused() => _readerRefusals.Add(1);

    /// <summary>Records a stream whose packaging started.</summary>
    public void SessionStarted() => _sessions.Add(1);

    /// <summary>Records a stream whose packaging ended.</summary>
    public void SessionEnded() => _sessions.Add(-1);

    /// <summary>Records an initialization segment.</summary>
    /// <param name="bytes">Its size.</param>
    public void Initialization(int bytes)
    {
        _initializations.Add(1);
        _segmentBytes.Add(bytes);
    }

    /// <summary>Records a media segment.</summary>
    /// <param name="bytes">Its size.</param>
    /// <param name="duration">Its duration.</param>
    /// <param name="boundary">Why it was closed.</param>
    /// <param name="keyframeWait">Media time spent beyond the target waiting for a sync sample.</param>
    public void Segment(int bytes, TimeSpan duration, HlsSegmentBoundary boundary, TimeSpan keyframeWait)
    {
        _segments.Add(1, new KeyValuePair<string, object?>("boundary", Name(boundary)));
        _segmentBytes.Add(bytes);
        _segmentDuration.Record(duration.TotalSeconds);
        if (keyframeWait > TimeSpan.Zero)
        {
            _keyframeWait.Record(keyframeWait.TotalSeconds);
        }
    }

    /// <summary>Records a change in stored bytes.</summary>
    /// <param name="delta">Bytes added (positive) or released (negative).</param>
    public void StorageChanged(long delta) => _storageBytes.Add(delta);

    /// <summary>Records evicted segments.</summary>
    /// <param name="reason">One of <c>retired</c>, <c>capacity</c>, <c>stream_closed</c> or <c>stream_expired</c>.</param>
    /// <param name="count">Number of segments.</param>
    public void Evicted(string reason, int count = 1) => _evictions.Add(count, new KeyValuePair<string, object?>("reason", reason));

    /// <summary>Records a packaging error.</summary>
    /// <param name="kind">The kind.</param>
    public void Error(HlsErrorKind kind) => _errors.Add(1, new KeyValuePair<string, object?>("kind", kind switch
    {
        HlsErrorKind.UnsupportedTrack => "unsupported_track",
        HlsErrorKind.InvalidTrack => "invalid_track",
        HlsErrorKind.SegmentTooLarge => "segment_too_large",
        HlsErrorKind.PlaylistFull => "playlist_full",
        _ => "storage_full",
    }));

    /// <summary>Records a playlist discontinuity.</summary>
    /// <param name="reason">One of <c>timestamp</c>, <c>configuration</c> or <c>dropped_media</c>.</param>
    public void Discontinuity(string reason) => _discontinuities.Add(1, new KeyValuePair<string, object?>("reason", reason));

    /// <summary>Records samples that were not packaged.</summary>
    /// <param name="video">Whether they are video samples.</param>
    /// <param name="reason">One of <c>before_sync_sample</c>, <c>untracked</c>, <c>too_large</c>, <c>storage_full</c>, <c>playlist_full</c>, <c>timeline_overlap</c> or <c>aborted</c>.</param>
    /// <param name="count">Number of samples.</param>
    public void SamplesDropped(bool video, string reason, int count = 1)
    {
        if (count > 0)
        {
            _droppedSamples.Add(count, new KeyValuePair<string, object?>("track", video ? "video" : "audio"), new KeyValuePair<string, object?>("reason", reason));
        }
    }

    /// <summary>Returns the tag value of a boundary.</summary>
    /// <param name="boundary">The boundary.</param>
    /// <returns>The tag value.</returns>
    private static string Name(HlsSegmentBoundary boundary) => boundary switch
    {
        HlsSegmentBoundary.Keyframe => "keyframe",
        HlsSegmentBoundary.Forced => "forced",
        HlsSegmentBoundary.Configuration => "configuration",
        HlsSegmentBoundary.Discontinuity => "discontinuity",
        _ => "final",
    };
}
